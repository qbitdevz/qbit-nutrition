/// <reference types="node" />
/**
 * Writes docs/catalog-translation-sample.md: 200 random composed Spanish names next to their English originals, so the
 * owner can judge the composer's quality. Reads catalog-build/catalog.db; the draw is seeded, so the same catalog gives the
 * same sample. Run: npx tsx scripts/catalog/translationSample.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const SEED = 20261121;
const SIZE = 200;
const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'docs', 'catalog-translation-sample.md');
const REVIEW = path.join(__dirname, 'data', 'translation-review.md');

const db = new DatabaseSync(path.join(ROOT, 'catalog-build', 'catalog.db'), { readOnly: true });
const names = db
  .prepare(
    `SELECT f.id AS id, f.source AS source, e.name AS en, s.name AS es, s.origin AS origin FROM food f
       JOIN food_name e ON e.food_id = f.id AND e.locale = 'en' AND e.is_alias = 0
       JOIN food_name s ON s.food_id = f.id AND s.locale = 'es' AND s.is_alias = 0 ORDER BY f.id`,
  )
  .all() as unknown as { id: number; source: string; en: string; es: string; origin: string }[];
const count = (o: string) => names.filter((n) => n.origin === o).length;
const composed = names.filter((n) => n.origin === 'composed');

let seed = SEED;
const rnd = (): number => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const pool = [...composed];
const sample: typeof composed = [];
while (sample.length < SIZE && pool.length > 0) sample.push(pool.splice(Math.floor(rnd() * pool.length), 1)[0] as (typeof composed)[number]);
sample.sort((a, b) => a.id - b.id);

const cell = (s: string): string => s.replace(/\|/g, '\|');
const pct = (n: number): string => `${((n / names.length) * 100).toFixed(1)} %`;
const review = (() => {
  try {
    return readFileSync(REVIEW, 'utf8').trim();
  } catch {
    return '';
  }
})();

const lines = [
  '# Catalog translation sample',
  '',
  'Generated by `npx tsx scripts/catalog/translationSample.ts` from `catalog-build/catalog.db` (seed ' + SEED + '). Do not edit the table by hand;',
  'the reviewer notes come from `scripts/catalog/data/translation-review.md`.',
  '',
  `${SIZE} foods drawn at random from the ${composed.length.toLocaleString('en')} whose Spanish name was **composed** by the glossary composer`,
  '(`scripts/catalog/compose.ts` + `scripts/catalog/data/glossary/`), next to their USDA English description. Spanish names are text only:',
  'no nutrient value is derived from them.',
  '',
  '## Numbers',
  '',
  '| | Foods | Share |',
  '| --- | ---: | ---: |',
  `| Foods in the catalog | ${names.length.toLocaleString('en')} | 100 % |`,
  `| With a Spanish display name | ${names.length.toLocaleString('en')} | ${pct(names.length)} |`,
  `| Composed by the glossary | ${count('composed').toLocaleString('en')} | ${pct(count('composed'))} |`,
  `| Handwritten (\`scripts/catalog/data/translations.es.json\`) | ${count('handwritten').toLocaleString('en')} | ${pct(count('handwritten'))} |`,
  '',
  ...(review ? [review, ''] : []),
  '## Sample',
  '',
  '| # | English (USDA) | Spanish (composed) |',
  '| ---: | --- | --- |',
  ...sample.map((n, i) => `| ${i + 1} | ${cell(n.en)} | ${cell(n.es)} |`),
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${OUT}: ${sample.length} of ${composed.length} composed names`);
