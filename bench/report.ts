/// <reference types="node" />
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { scrub, slug, writeJsonSafe } from './cache';
import type { BenchReport, Metrics } from './types';

export const SUMMARY_HEADER =
  '| Model | Prompt | Item recall | Portion error | Energy error | Within ±20% | Valid output | Median latency | Tokens per scan | Meals |';

const pct = (v: number | null) => (v === null ? 'n/a' : `${(v * 100).toFixed(1)}%`);
const pct0 = (v: number | null) => (v === null ? 'n/a' : `${Math.round(v * 100)}%`);
const seconds = (v: number | null) => (v === null ? 'n/a' : `${(v / 1000).toFixed(1)} s`);
const tokens = (m: Metrics) =>
  m.inputTokensPerScan === null || m.outputTokensPerScan === null
    ? 'n/a'
    : `${Math.round(m.inputTokensPerScan).toLocaleString('en-US')} in / ${Math.round(m.outputTokensPerScan).toLocaleString('en-US')} out`;

function mealsCell(r: BenchReport): string {
  const { total, food, nonFood } = r.datasetSize;
  const extra = [r.subset === 'smoke' ? 'smoke subset' : null, r.metrics.counts.failed > 0 ? `${r.metrics.counts.failed} failed` : null].filter(Boolean);
  return `${total} meals (${food} food, ${nonFood} non-food${extra.length ? `; ${extra.join('; ')}` : ''})`;
}

const cell = (text: string) => text.replace(/\|/g, '\\|');

export function summaryRow(r: BenchReport): string {
  const m = r.metrics;
  return `| ${[
    cell(r.model),
    `v${r.promptVersion}`,
    pct(m.itemRecall),
    pct(m.portionMape),
    pct(m.energyMape),
    pct(m.within20),
    `${pct0(m.validFirstAttempt)} first / ${pct0(m.validAfterRepair)} after repair`,
    seconds(m.latencyMedianMs),
    tokens(m),
    mealsCell(r),
  ].join(' | ')} |`;
}

/** The docs/11 B.4 table: one row per model and prompt version. */
export function renderSummary(reports: readonly BenchReport[]): string {
  const rows = [...reports].sort((a, b) => a.model.localeCompare(b.model) || a.promptVersion - b.promptVersion);
  return [
    '# Benchmark summary',
    '',
    'Generated by `npx tsx bench/run.ts`. Errors are mean absolute percentage errors; portion error covers',
    'correctly identified items only; energy error covers meals with a valid answer; "Within ±20%" counts',
    'meals with no usable answer as misses. See `bench/README.md` for the definitions.',
    '',
    SUMMARY_HEADER,
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(summaryRow),
    '',
  ].join('\n');
}

export const resultsFileName = (r: Pick<BenchReport, 'model' | 'promptVersion'>) => `results-${slug(r.model)}-v${r.promptVersion}.json`;

function isReport(value: unknown): value is BenchReport {
  const v = value as BenchReport | null;
  return !!v && typeof v.model === 'string' && typeof v.promptVersion === 'number' && !!v.metrics && !!v.datasetSize;
}

/** Writes this run's results file, then rebuilds `summary.md` from every results file in the folder. */
export function writeReport(outDir: string, report: BenchReport, secret: string | null): { resultsPath: string; summaryPath: string } {
  const resultsPath = path.join(outDir, resultsFileName(report));
  writeJsonSafe(resultsPath, report, secret);

  const all: BenchReport[] = [];
  for (const name of readdirSync(outDir)) {
    if (!/^results-.*\.json$/.test(name)) continue;
    try {
      const parsed: unknown = JSON.parse(readFileSync(path.join(outDir, name), 'utf8'));
      if (isReport(parsed)) all.push(parsed);
    } catch {
      // a damaged results file is skipped, not fatal
    }
  }
  const summaryPath = path.join(outDir, 'summary.md');
  writeFileSync(summaryPath, scrub(renderSummary(all), secret), 'utf8');
  return { resultsPath, summaryPath };
}
